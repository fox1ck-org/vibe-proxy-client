// Про gateway и почему здесь больше нет конструктора его адреса.
//
// Раньше клиент собирал адрес gateway сам:
//
//	GatewayProxyURL(host, port, consumerID, apiKey)
//
// — имя потребителя плюс ОДИН общий API-ключ на всех. Такой адрес принимал кто
// угодно с ключом под любым именем и тратил чужой трафик; вдобавок потребитель
// решал за сервер, каким маршрутом идти, и мог разойтись с ним во мнениях.
//
// Теперь маршрут — свойство ПУЛА (`routing_mode`), и адрес всегда приходит
// готовым в ответе на аренду:
//
//	lease, err := client.AcquireLease(ctx, input)
//	proxyURL := lease.Connection.ProxyURL   // апстрим или gateway — решает пул
//
// Потребителю не нужно знать, какой это случай: для пула с маршрутом через
// gateway в Connection лежит адрес gateway и удостоверение ЭТОЙ аренды
// (username = id аренды), а выходной IP по-прежнему доступен как
// Connection.ExternalIP.
